fun main()
{
    var i: Int
    i = 22
    println("Integer value:"+i)

    var j: Float
    j = 1.5f
    println("Float value:"+j)

    var ch: Char
    ch = 'T'
    println("Character value:"+ch)

    var string: String
    string = "HMS"
    println("""String value:"""+string)

    var k: Boolean
    k = true
    println("Boolean value:"+k)

    var d: Double
    d = 96.36
    println("Double value:"+d)

    var l: Long
    l = 33859754554
    println("Long value:"+l)

    var s: Short
    s = -2
    println("Short value:"+s)

    var b: Byte
    b = 127
    println("Byte value:"+b)

    println("Sum ${5 + 7}")
}